        'admin_email' => trim($_POST['admin_email'] ?? ''),
        'admin_pass' => $_POST['admin_pass'] ?? '',
        'admin_pass2' => $_POST['admin_pass2'] ?? '',
        'timezone' => trim($_POST['timezone'] ?? 'UTC'),
        'force_https' => !empty($_POST['force_https']),
        'trusted_proxies' => trim($_POST['trusted_proxies'] ?? ''),
        'allowed_hosts' => trim($_POST['allowed_hosts'] ?? ''),
    ];
    if (!filter_var($p['admin_email'], FILTER_VALIDATE_EMAIL)) {
        $errors[] = 'A valid admin email is required.';
    }
    if (strlen($p['admin_pass']) < 8) {
        $errors[] = 'Admin password must be at least 8 characters.';
    }
    if ($p['admin_pass'] !== $p['admin_pass2']) {
        $errors[] = 'Passwords do not match.';
    }
    if (empty($p['db_host']) || empty($p['db_user']) || empty($p['db_name'])) {
        $errors[] = 'Database host, user and name are required.';
    }
    if (!$errors) {
        $res = runInstall($p);
        if ($res) {
            $errors = array_merge($errors, $res);
        } else {
            $success = 'Installed successfully.';
        }
    }
}

