// ---------------------------------------------------------------- helpers
function env_escape(string $v): string
{
    // Escape value for a simple KEY=VALUE .env file.
    if (preg_match('/[^A-Za-z0-9 _.\\-\\/:@]/', $v)) {
        return '"' . str_replace(['\\\\', '"'], ['\\\\\\\\', '\\"'], $v) . '"';
    }
    return $v;
}

function checkPreflight(): array
{
    $problems = [];
    if (PHP_VERSION_ID < 80100) {
        $problems[] = 'PHP 8.1+ required (you have ' . PHP_VERSION . ').';
    }
    foreach (['mysqli', 'mbstring', 'openssl', 'json', 'curl', 'zip'] as $ext) {
        if (!extension_loaded($ext)) {
            $problems[] = "PHP extension <code>$ext</code> is not enabled.";
        }
    }
    if (!is_writable(APP_ROOT) && !is_writable(ENV_FILE)) {
        $problems[] = 'The application directory must be writable so we can create <code>.env</code>.';
    }
    if (!is_file(SCHEMA_FILE)) {
        $problems[] = 'Schema file <code>database/schema.sql</code> is missing.';
    }
    if (!class_exists('mysqli')) {
        $problems[] = 'mysqli class unavailable.';
    }
    return $problems;
}

function runInstall(array $p): array
{
    $errs = [];
    // 1) connect
    $mysqli = @new mysqli($p['db_host'], $p['db_user'], $p['db_pass'], $p['db_name'], (int) $p['db_port']);
    if ($mysqli->connect_error) {
        return ['Cannot connect to MySQL: ' . $mysqli->connect_error];
    }
    $mysqli->set_charset('utf8mb4');

    // 2) import schema
    $sql = @file_get_contents(SCHEMA_FILE);
    if ($sql === false) {
        return ['Cannot read schema file.'];
    }
    // Split on ; that is followed by newline (statement boundary) to be safe.
    $statements = preg_split('/;\\s*\\n/', $sql);
    foreach ($statements as $stmt) {
        $stmt = trim($stmt);
        if ($stmt === '' || str_starts_with($stmt, '--') || str_starts_with($stmt, 'SET ')) {
            // still execute SET statements
            if (str_starts_with($stmt, 'SET ')) {
                $mysqli->query($stmt);
            }
            continue;
        }
        if (!$mysqli->query($stmt)) {
            $errs[] = 'SQL error: ' . $mysqli->error . ' — in: ' . substr($stmt, 0, 80);
        }
    }
    if ($errs) {
        return $errs;
    }

    // 3) seed admin user (bcrypt)
    $email = $mysqli->real_escape_string(strtolower(trim($p['admin_email'])));
    $hash = password_hash($p['admin_pass'], PASSWORD_BCRYPT, ['cost' => 12]);
    $name = $mysqli->real_escape_string(trim($p['admin_name']));
    $apiKey = bin2hex(random_bytes(24));
    $tz = $mysqli->real_escape_string($p['timezone']);
    $mysqli->query("INSERT INTO `User` (`name`,`email`,`password`,`isAdmin`,`apiKey`,`dateAdded`,`timeZone`,`credits`)
        VALUES ('$name','$email','$hash',1,'$apiKey',NOW(),'$tz',NULL)");

    // 4) write .env
    $env = [
        'APP_ENV' => 'production',
        'APP_SECRET_KEY' => bin2hex(random_bytes(32)),
        'APP_SESSION_NAME' => 'SMS_GATEWAY',
        'DB_SERVER' => $p['db_host'],
        'DB_PORT' => (string) $p['db_port'],
        'DB_USER' => $p['db_user'],
        'DB_PASS' => $p['db_pass'],
        'DB_NAME' => $p['db_name'],
        'TIMEZONE' => $p['timezone'],
        'FORCE_HTTPS' => $p['force_https'] ? 'true' : 'false',
        'TRUSTED_PROXIES' => $p['trusted_proxies'],
        'ALLOWED_HOSTS' => $p['allowed_hosts'],
        'LOGIN_MAX_ATTEMPTS' => '5',
        'LOGIN_LOCKOUT_SECONDS' => '900',
    ];
    $out = "# SMS Gateway environment — generated by the installer. Do not commit.\n";
    foreach ($env as $k => $v) {
        $out .= $k . '=' . env_escape($v) . "\n";
    }
    if (@file_put_contents(ENV_FILE, $out) === false) {
        return ['Could not write <code>.env</code>. Check directory permissions.'];
    }
    @chmod(ENV_FILE, 0600);

    // 5) lock the installer
    @file_put_contents(LOCK_FILE, date('c'));
    return [];
}

